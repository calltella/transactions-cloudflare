import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../supabase/', import.meta.url));
const migrations = [
  '202610110001_transactions_work_rls.sql',
  '202610110007_insert_normalized_transactions.sql',
  '20261013200858_auth_app_metadata_admin.sql',
  '202610110008_bank_accounts.sql',
  '202610110009_dashboard_settings.sql',
  '202610110010_dashboard_start_holiday.sql',
  '20261013194330_bank_transfers.sql',
  '20261013204354_create_bank_account.sql',
  '20261013205800_account_display_order.sql',
  '20261013210505_bank_monthly_balances.sql',
  '20261013214908_card_deferred_billing.sql',
  '20261013221205_monthly_opening_override.sql',
  '20261014093102_cash_accounts.sql',
];
const parts = [await readFile(path.join(root, 'schema.sql'), 'utf8')];
for (const name of migrations) {
  let sql = await readFile(path.join(root, 'migrations', name), 'utf8');
  sql = sql.replace(/^begin;\s*$/gmi, '').replace(/^commit;\s*$/gmi, '')
    .replace(/^notify pgrst, 'reload schema';\s*$/gmi, '');
  if (name === '202610110009_dashboard_settings.sql') {
    sql = sql.replace('create table public.dashboard_settings', 'create table if not exists public.dashboard_settings')
      .replace(/^(create policy (\w+) on public\.dashboard_settings)/gm, 'drop policy if exists $2 on public.dashboard_settings;\n$1');
  }
  parts.push(`-- Source: migrations/${name}\n${sql.trim()}\n`);
}
for (const environment of ['production', 'local']) {
  const sql = `-- Generated by npm run supabase:setup. Edit schema.sql / migrations, then regenerate.
-- ${environment} Supabase: run this whole file once in SQL Editor (or psql).
-- Requires Supabase's auth.users, auth.uid(), authenticated and anon roles.
-- Administrators: Auth app_metadata.role = "admin" (configured separately).
-- Existing records are preserved. Normalization/import RPCs are defined, never called.
begin;

${parts.join('\n')}
notify pgrst, 'reload schema';
commit;
`;
  const filename = path.join(root, environment, 'setup.sql');
  if (process.argv.includes('--check')) {
    if (await readFile(filename, 'utf8') !== sql) throw new Error(`${environment}/setup.sql is stale; run npm run supabase:setup`);
  } else await writeFile(filename, sql);
}
