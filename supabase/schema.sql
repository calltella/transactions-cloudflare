-- Shared base schema. Use local/setup.sql or production/setup.sql for installation.
create table if not exists public.transaction_types (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.payment_methods (
  id bigint generated by default as identity primary key,
  name text not null unique,
  type text not null default 'other',
  created_at timestamptz not null default now()
);
create table if not exists public.parent_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);
create table if not exists public.child_categories (
  id bigint generated by default as identity primary key,
  parent_category_id bigint not null references public.parent_categories(id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now(),
  unique (parent_category_id, name)
);
create table if not exists public.transactions_work (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  date date not null,
  type text not null,
  payment_method text,
  parent_category text,
  child_category text,
  amount integer,
  location text,
  memo text,
  note text,
  tag text,
  created_at timestamptz not null default now()
);
create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  date date not null,
  type_id bigint references public.transaction_types(id),
  payment_method_id bigint references public.payment_methods(id),
  parent_category_id bigint references public.parent_categories(id),
  child_category_id bigint references public.child_categories(id),
  amount integer,
  location text,
  memo text,
  note text,
  tag text,
  created_at timestamptz not null default now()
);
create index if not exists transactions_user_date_id_idx on public.transactions(user_id, date, id);

-- Income/expense are required before the first manual transaction or bank transfer.
insert into public.transaction_types(name) values ('収入'), ('支出') on conflict (name) do nothing;

create table if not exists public.credit_cards (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  payment_method_id bigint not null references public.payment_methods(id),
  closing_day smallint check (closing_day between 0 and 31),
  payment_day smallint check (payment_day between 0 and 31),
  payment_month_offset smallint not null default 1 check (payment_month_offset >= 0),
  bank_account_payment_method_id bigint references public.payment_methods(id),
  is_active boolean not null default true,
  memo text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, payment_method_id)
);
alter table public.credit_cards enable row level security;
alter table public.credit_cards force row level security;
drop policy if exists credit_cards_owner_guard on public.credit_cards;
create policy credit_cards_owner_guard on public.credit_cards as restrictive for all to public
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists credit_cards_owner_access on public.credit_cards;
create policy credit_cards_owner_access on public.credit_cards for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.credit_cards to authenticated;
grant usage, select on sequence public.credit_cards_id_seq to authenticated;
revoke all on public.credit_cards from anon;
create or replace function public.credit_cards_set_updated_at()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin new.updated_at := now(); return new; end;
$$;
drop trigger if exists credit_cards_updated_at on public.credit_cards;
create trigger credit_cards_updated_at before update on public.credit_cards
  for each row execute function public.credit_cards_set_updated_at();

-- Shared masters: authenticated reads; rebuilding is restricted by each RPC.
do $$
declare table_name text;
begin
  foreach table_name in array array['transaction_types', 'payment_methods', 'parent_categories', 'child_categories'] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on public.%I from anon', table_name);
  end loop;
end $$;
