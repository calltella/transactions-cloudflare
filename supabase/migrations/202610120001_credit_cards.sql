-- Run in the connected Supabase SQL Editor to enable cards and the dashboard.
-- Creates configuration only; does not insert, delete, or normalize transactions.
begin;

create table if not exists public.credit_cards (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  payment_method_id bigint not null references public.payment_methods (id),
  closing_day smallint null check (closing_day between 0 and 31),
  payment_day smallint null check (payment_day between 0 and 31),
  payment_month_offset smallint not null default 1 check (payment_month_offset >= 0),
  bank_account_payment_method_id bigint null references public.payment_methods (id),
  is_active boolean not null default true,
  memo text null check (char_length(memo) <= 5000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint credit_cards_user_payment_method_unique unique (user_id, payment_method_id)
);

alter table public.credit_cards enable row level security;
alter table public.credit_cards force row level security;
drop policy if exists credit_cards_owner_guard on public.credit_cards;
create policy credit_cards_owner_guard on public.credit_cards
  as restrictive for all to public
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
drop policy if exists credit_cards_owner_access on public.credit_cards;
create policy credit_cards_owner_access on public.credit_cards
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.credit_cards to authenticated;
grant usage, select on sequence public.credit_cards_id_seq to authenticated;
revoke all on public.credit_cards from anon;

create or replace function public.credit_cards_set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists credit_cards_updated_at on public.credit_cards;
create trigger credit_cards_updated_at before update on public.credit_cards
  for each row execute function public.credit_cards_set_updated_at();

notify pgrst, 'reload schema';
commit;
