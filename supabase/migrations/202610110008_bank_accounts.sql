begin;
create table if not exists public.bank_accounts (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  payment_method_id bigint not null references public.payment_methods (id),
  bank_name text null,
  branch_name text null,
  account_holder text null,
  opening_balance bigint null check (opening_balance between -9007199254740991 and 9007199254740991),
  opening_balance_date date null,
  is_active boolean not null default true,
  memo text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint bank_accounts_user_payment_method_unique unique (user_id, payment_method_id),
  constraint bank_accounts_opening_balance_pair check (
    (opening_balance is null) = (opening_balance_date is null)
  )
);
-- Extend older installations without deleting their records.
alter table public.bank_accounts
  add column if not exists bank_name text,
  add column if not exists branch_name text,
  add column if not exists account_holder text,
  add column if not exists opening_balance bigint,
  add column if not exists opening_balance_date date,
  add column if not exists is_active boolean not null default true,
  add column if not exists memo text;
do $$
begin
  if exists (select 1 from information_schema.columns where table_schema = 'public'
    and table_name = 'bank_accounts' and column_name = 'account_name') then
    -- Display names now come from payment_methods; retain legacy values.
    alter table public.bank_accounts alter column account_name drop not null;
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.bank_accounts'::regclass and conname = 'bank_accounts_user_payment_method_unique') then
    alter table public.bank_accounts add constraint bank_accounts_user_payment_method_unique unique (user_id, payment_method_id);
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.bank_accounts'::regclass and conname = 'bank_accounts_opening_balance_pair') then
    alter table public.bank_accounts add constraint bank_accounts_opening_balance_pair check ((opening_balance is null) = (opening_balance_date is null));
  end if;
end $$;
alter table public.bank_accounts drop constraint if exists bank_accounts_opening_balance_check;
alter table public.bank_accounts add constraint bank_accounts_opening_balance_check
  check (opening_balance between -9007199254740991 and 9007199254740991);
alter table public.bank_accounts enable row level security;
alter table public.bank_accounts force row level security;
drop policy if exists bank_accounts_owner_guard on public.bank_accounts;
create policy bank_accounts_owner_guard on public.bank_accounts
  as restrictive for all to public
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists bank_accounts_owner_access on public.bank_accounts;
create policy bank_accounts_owner_access on public.bank_accounts
  for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.bank_accounts to authenticated;
grant usage, select on sequence public.bank_accounts_id_seq to authenticated;
revoke all on public.bank_accounts from anon;
create or replace function public.bank_accounts_set_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists bank_accounts_updated_at on public.bank_accounts;
create trigger bank_accounts_updated_at before update on public.bank_accounts
  for each row execute function public.bank_accounts_set_updated_at();
notify pgrst, 'reload schema';
commit;
